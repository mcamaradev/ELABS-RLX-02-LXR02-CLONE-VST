#!/usr/bin/env python3
"""Packs the built-in kits (kits/elabs: the ELABS kits written by src/elabs_kits.rs, then the
EntropiaLabs kits in kits/elabs/ENTROPIA) into kits/lxr_kits.bin and writes src/kit_table.rs. The LXR-02 factory content is not
built in: users import it from Erica Synths' downloads (browser IMPORT).

A .snd file is an 8 byte name followed by the front panel parameter values (firmware
preset_loadDrumsetSD). Duplicates (same values) and empty init kits are left out.

usage: gen_kits.py kits kits/lxr_kits.bin src/kit_table.rs
"""
import hashlib
import os
import re
import sys

src, bin_path, rs_path = sys.argv[1:4]
NUM_PARAMS = 247

# bank name -> folders (relative to src), in browsing order
BANKS = [
    ("ELABS", ["elabs"]),
]
VALID_NAME = re.compile(r"^[A-Za-z0-9 !_\-.]+$")

seen = set()
kits = []
for bank, folders in BANKS:
    for folder in folders:
        for root, dirs, files in os.walk(os.path.join(src, folder)):
            dirs.sort()
            for f in sorted(files):
                if not f.upper().endswith(".SND"):
                    continue
                raw = open(os.path.join(root, f), "rb").read()
                name = raw[:8].split(b"\0")[0].decode("latin1").strip()
                data = raw[8:8 + NUM_PARAMS].ljust(NUM_PARAMS, b"\0")
                if not VALID_NAME.match(name) or name.upper().startswith("INIT"):
                    continue
                digest = hashlib.sha1(data).digest()
                if digest in seen:
                    continue
                seen.add(digest)
                kits.append((bank, name, data))

with open(bin_path, "wb") as out:
    for _, _, data in kits:
        out.write(data)

lines = [
    "// Generated by tools/gen_kits.py from kits/elabs. Do not edit.",
    "",
    f"pub const KIT_SIZE: usize = {NUM_PARAMS};",
    'pub static KIT_DATA: &[u8] = include_bytes!("../kits/lxr_kits.bin");',
    "",
    "/// (bank, name) of each kit in KIT_DATA, in order",
    "pub static KITS: &[(&str, &str)] = &[",
]
lines += [f'    ("{bank}", "{name}"),' for bank, name, _ in kits]
lines.append("];")
open(rs_path, "w").write("\n".join(lines) + "\n")
for bank, _ in BANKS:
    print(bank, sum(1 for k in kits if k[0] == bank))
