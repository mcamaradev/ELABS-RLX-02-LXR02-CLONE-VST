#!/usr/bin/env python3
"""Packs the built-in projects (64 patterns + 64 kit slots each: the ELABS demo project written by
src/elabs_kits.rs and the ENTROPIA project, both in kits/elabs) into kits/lxr_projects.bin and
writes src/project_table.rs.

Patterns (.pat) are converted to version 3 (firmware preset_readPatternData): name, "PatV03",
per track 64 steps of 7 bytes followed by 64 timing bytes, then 7 x 4 x u16 main steps, shuffle,
7 track lengths and the kit number. Version 2 files have no timing bytes: those become
flam 0 / shift 7 (no shift), like a cleared pattern. Kits are .snd files: 8 byte name + 247 values.

usage: gen_projects.py kits kits/lxr_projects.bin src/project_table.rs
"""
import os
import re
import sys

src, bin_path, rs_path = sys.argv[1:4]

TRACKS, STEPS, BARS = 7, 64, 4
STEP_BYTES = 7
PATTERN_BYTES = 8 + 6 + TRACKS * STEPS * (STEP_BYTES + 1) + TRACKS * BARS * 2 + 1 + TRACKS + 1
KIT_BYTES = 247
SLOTS = 64
NO_TIMING = 0x70  # flam 0 (low nibble), shift 7 = none (high nibble)

PROJECTS = [
    ("ELABS", "elabs/ELABS"),
    ("ENTROPIA", "elabs/ENTROPIA"),
]


def to_v3(raw):
    pos, version = 8, 1
    if raw[8:12] == b"PatV":
        version, pos = int(raw[12:14]), 14
    out = bytearray(b"\0" * 8 + b"PatV03")
    for _ in range(TRACKS):
        out += raw[pos:pos + STEPS * STEP_BYTES]
        pos += STEPS * STEP_BYTES
        if version > 2:
            out += raw[pos:pos + STEPS]
            pos += STEPS
        else:
            out += bytes([NO_TIMING]) * STEPS
    rest = raw[pos:pos + TRACKS * BARS * 2 + 1 + TRACKS]
    out += rest
    out += raw[pos + len(rest):pos + len(rest) + 1] if version > 1 else b"\0"
    if len(out) != PATTERN_BYTES:
        raise SystemExit(f"bad pattern size {len(out)}")
    return bytes(out)


def empty_pattern():
    """What src/seq.rs empty_pattern() makes (the firmware's cleared pattern): slots without a file
    get it, so every pattern in the file is one the firmware can play (no track length 0)."""
    out = bytearray(b"\0" * 8 + b"PatV03")
    for _ in range(TRACKS):
        for k in range(STEPS):
            out += bytes([0x80 | 127 if k % 8 == 0 else 127, 100, 60, 0xFF, 0, 0xFF, 0])
        out += bytes([NO_TIMING]) * STEPS
    out += b"\0" * (TRACKS * BARS * 2) + b"\0" + bytes([16]) * TRACKS + b"\0"
    assert len(out) == PATTERN_BYTES
    return bytes(out)


EMPTY_PATTERN = empty_pattern()


def slot(fname):
    m = re.match(r"^(\d\d)-", fname)
    return int(m.group(1)) if m else None


blob = bytearray()
lines = [
    "// Generated by tools/gen_projects.py from kits/elabs. Do not edit.",
    "",
    f"pub const PATTERN_BYTES: usize = {PATTERN_BYTES};",
    f"pub const KIT_BYTES: usize = {KIT_BYTES};",
    f"pub const SLOTS: usize = {SLOTS};",
    "/// per project: 64 patterns, then 64 kits",
    f"pub const PROJECT_BYTES: usize = {SLOTS * (PATTERN_BYTES + KIT_BYTES)};",
    'pub static PROJECT_DATA: &[u8] = include_bytes!("../kits/lxr_projects.bin");',
    "",
    "pub struct ProjectInfo {",
    "    pub name: &'static str,",
    "    /// which pattern slots came with a file (the others are empty patterns)",
    "    pub has_pattern: [bool; SLOTS],",
    "    /// kit name per slot, \"\" where the project has no kit",
    "    pub kit_names: [&'static str; SLOTS],",
    "}",
    "",
    "pub static PROJECTS: &[ProjectInfo] = &[",
]
for name, folder in PROJECTS:
    path = os.path.join(src, folder)
    patterns, kits = [None] * SLOTS, [None] * SLOTS
    for f in sorted(os.listdir(path)):
        n = slot(f)
        if n is None or n >= SLOTS:
            continue
        raw = open(os.path.join(path, f), "rb").read()
        if f.upper().endswith(".PAT"):
            patterns[n] = to_v3(raw)
        elif f.upper().endswith(".SND"):
            kit_name = raw[:8].split(b"\0")[0].decode("latin1").strip()
            kit_name = "".join(c if c.isprintable() and c != '"' and c != "\\" else "?" for c in kit_name)
            kits[n] = (kit_name, raw[8:8 + KIT_BYTES].ljust(KIT_BYTES, b"\0"))
    for p in patterns:
        blob += p if p else EMPTY_PATTERN
    for k in kits:
        blob += k[1] if k else b"\0" * KIT_BYTES
    has = ", ".join("true" if p else "false" for p in patterns)
    names = ", ".join('"%s"' % (k[0] if k else "") for k in kits)
    lines.append(f'    ProjectInfo {{ name: "{name}", has_pattern: [{has}], kit_names: [{names}] }},')
    print(f"{name}: {sum(1 for p in patterns if p)} patterns, {sum(1 for k in kits if k)} kits")
lines.append("];")
open(bin_path, "wb").write(blob)
open(rs_path, "w").write("\n".join(lines) + "\n")
print(f"{bin_path}: {len(blob)} bytes")
