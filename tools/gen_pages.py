#!/usr/bin/env python3
"""Builds src/ui_pages.rs (what the LXR's LCD shows per voice and sub page) from gen_pages.c output."""
import sys

dump_path, out_path = sys.argv[1:3]
skip = set()
pages = {}
mod_targets = []
for line in open(dump_path):
    f = line.rstrip("\n").split("\t")
    if f[0] == "MODTARGET":
        mod_targets.append((int(f[2]), int(f[3]), f[4].strip(), f[6].strip()))
        continue
    if f[0] in ("TEXT_EMPTY", "TEXT_SKIP"):
        skip.add(int(f[1]))
        continue
    page, sub, slot, text, param = f[0], int(f[1]), int(f[2]), int(f[3]), int(f[4])
    short, cat, long_ = f[5], f[6], f[7]
    pages.setdefault(page, {})[(sub, slot)] = None if text in skip else (param, short.strip(), cat.strip(), long_.strip())


def slot_rs(s):
    if s is None:
        return "None"
    param, short, cat, long_ = s
    return f'Some(Slot {{ param: {param}, short: "{short}", category: "{cat}", long: "{long_}" }})'


def page_rs(name, subs):
    rows = []
    for sub in range(subs):
        rows.append("        [" + ", ".join(slot_rs(pages[name].get((sub, i))) for i in range(8)) + "],")
    return "\n".join(rows)


out = ["// Generated by tools/gen_pages.py from the LXR firmware's menuPages. Do not edit.", "",
       "#[derive(Clone, Copy)]",
       "pub struct Slot {",
       "    /// firmware parameter index",
       "    pub param: u16,",
       "    pub short: &'static str,",
       "    pub category: &'static str,",
       "    pub long: &'static str,",
       "}", "",
       "pub type SubPage = [Option<Slot>; 8];", "",
       "/// Drum 1, Drum 2, Drum 3, Snare, Cymbal, Hihat closed, Hihat open; sub pages",
       "/// OSC, AEG, MOD, FM, CLICK, FILTER, LFO, MIX",
       "pub static VOICE_PAGES: [[SubPage; 8]; 7] = ["]
for v in range(1, 8):
    out.append("    [")
    out.append(page_rs(f"VOICE{v}", 8))
    out.append("    ],")
out.append("];")
out.append("")
out.append("/// One sub page per FX type (off, drive, ring mod, compressor, delay, reverb)")
out.append("pub static FX_PAGES: [SubPage; 6] = [")
out.append(page_rs("FX", 6).replace("        [", "    [", ))
out.append("];")
out.append("")
out.append("pub struct ModTarget {")
out.append("    /// firmware parameter index the modulation goes to")
out.append("    pub param: u16,")
out.append("    /// 1-6 = the voice whose parameter it is, 0 = none/global")
out.append("    pub voice: u8,")
out.append("    pub short: &'static str,")
out.append("    pub long: &'static str,")
out.append("}")
out.append("")
out.append("/// The firmware's modTargets table: LFO and velocity destinations, stored in kits by index.")
out.append("pub static MOD_TARGETS: &[ModTarget] = &[")
for param, voice, short, long_ in mod_targets:
    out.append(f'    ModTarget {{ param: {param}, voice: {voice}, short: "{short}", long: "{long_}" }},')
out.append("];")
open(out_path, "w").write("\n".join(out) + "\n")
